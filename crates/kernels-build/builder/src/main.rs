//! `cargo xtask kernels`: compile the shader crate to SPIR-V and write it into
//! `crates/kernels/spv/` (committed, doc 04 Q28).
//!
//! With `--check`, build into a temporary location and fail if the committed module
//! differs (used by CI).

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use spirv_builder::SpirvBuilder;

const TARGET: &str = "spirv-unknown-vulkan1.2";
const OUT_NAME: &str = "aigle_kernels.spv";

fn main() -> ExitCode {
    let check = std::env::args().any(|a| a == "--check");
    let here = Path::new(env!("CARGO_MANIFEST_DIR"));
    let shader = here.join("../shader");
    let out_dir = here.join("../../kernels/spv");

    let result = match SpirvBuilder::new(&shader, TARGET).release(true).build() {
        Ok(r) => r,
        Err(e) => {
            eprintln!("SPIR-V build failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let built: PathBuf = result.module.unwrap_single().to_path_buf();
    let bytes = std::fs::read(&built).expect("read built module");
    let mut entries = result.entry_points.clone();
    entries.sort();
    let manifest = format!(
        "# Generated by `cargo xtask kernels`; do not edit.\n\
         # rust-gpu spirv-builder 0.11.0, target {TARGET}\n\
         module = \"{OUT_NAME}\"\n\
         bytes = {}\n\
         entry_points = [{}]\n",
        bytes.len(),
        entries.iter().map(|e| format!("\"{e}\"")).collect::<Vec<_>>().join(", ")
    );

    let spv_path = out_dir.join(OUT_NAME);
    let manifest_path = out_dir.join("manifest.toml");
    if check {
        let same = std::fs::read(&spv_path).ok().as_deref() == Some(&bytes[..])
            && std::fs::read_to_string(&manifest_path).ok().as_deref() == Some(&manifest[..]);
        if same {
            println!("committed SPIR-V is up to date");
            return ExitCode::SUCCESS;
        }
        eprintln!("committed SPIR-V in {} is stale; run `cargo xtask kernels`", out_dir.display());
        return ExitCode::FAILURE;
    }
    std::fs::create_dir_all(&out_dir).expect("create spv dir");
    std::fs::write(&spv_path, &bytes).expect("write module");
    std::fs::write(&manifest_path, manifest).expect("write manifest");
    println!("wrote {} ({} bytes, entry points: {})", spv_path.display(), bytes.len(), entries.join(", "));
    ExitCode::SUCCESS
}
